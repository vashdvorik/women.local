@props(['profile', 'page' => false, 'part' => 'all'])

{{--
    Кнопки модерации профиля участницы: «Видима другим / Скрыта от других», «Режим невидимки» и особая «Заблокировать /
    Разблокировать». У каждой есть подсказка при наведении и окно подтверждения, где написано, что именно произойдёт.
    part: 'switches' — два переключателя для таблицы, 'lock' — только блокировка (таблица), 'all' — всё кнопками (страница профиля).
--}}
@php
    $name = $profile->full_name ?: __('Участница');
    $blocked = $profile->isRejected();
    $approved = $profile->isApproved();
    $hidden = (bool) $profile->is_hidden;
    $asSwitch = $part === 'switches';
    $quiet = $page ? 'btn-secondary' : 'btn-quiet';
@endphp

@if($part !== 'lock' && ! $blocked)
    {{-- Видимость другим участницам (профиль в каталоге, поиске, подборе контактов и AI-помощнике) --}}
    @if($approved)
        <x-admin.confirm-button
            :action="route('admin.profiles.unapprove', $profile)"
            :label="$asSwitch ? __('Видима другим') : __('Скрыть от других')"
            :toggle="$asSwitch ? true : null"
            :trigger="$quiet"
            :hint="__('Сейчас профиль виден другим участницам. Нажмите, чтобы убрать его из каталога, поиска и подбора. Её кабинет, пакет и рассылки не меняются.')"
            :title="__('Скрыть профиль от других участниц? (:name)', ['name' => $name])"
            :confirm="__('Скрыть от других')"
            :message="__('Профиль пропадёт из каталога, поиска, подбора контактов и AI-помощника других участниц. Сама участница продолжит пользоваться кабинетом, её пакет и рассылки не меняются. Уведомление ей не отправляется. Вернуть видимость можно в любой момент.')" />
    @else
        <x-admin.confirm-button
            :action="route('admin.profiles.approve', $profile)"
            :label="$asSwitch ? __('Скрыта от других') : __('Показать другим')"
            :toggle="$asSwitch ? false : null"
            :trigger="$quiet"
            :hint="__('Сейчас профиль скрыт от других участниц. Нажмите, чтобы показать его в каталоге, поиске и подборе (пока у неё действует платный пакет).')"
            :title="__('Сделать профиль видимым другим? (:name)', ['name' => $name])"
            :confirm="__('Показать другим')"
            :message="__('Профиль появится в каталоге, поиске, подборе контактов и AI-помощнике других участниц, но только пока у неё действует платный пакет и не включён режим невидимки. Уведомление ей не отправляется.')" />
    @endif

    {{-- Режим невидимки: человек внутри платформы, но другие его не видят и не находят --}}
    @if($hidden)
        <x-admin.confirm-button
            :action="route('admin.profiles.visibility', $profile)"
            :label="$asSwitch ? __('Режим невидимки') : __('Режим невидимки: вкл')"
            :toggle="$asSwitch ? true : null"
            :trigger="$quiet.' font-semibold'"
            :hint="__('Режим невидимки включён: другие участницы её не видят и не находят. Нажмите, чтобы выключить.')"
            :title="__('Выключить режим невидимки? (:name)', ['name' => $name])"
            :confirm="__('Выключить')"
            :message="__('Профиль снова станет виден другим участницам, если он помечен как видимый и у неё действует платный пакет. После выключения она снова сможет публиковать инициативы. Уведомление не отправляется.')" />
    @else
        <x-admin.confirm-button
            :action="route('admin.profiles.visibility', $profile)"
            :label="__('Режим невидимки')"
            :toggle="$asSwitch ? false : null"
            :trigger="$quiet"
            :hint="__('Для администраторов, спонсоров и партнёров: человек остаётся внутри платформы, но другие его не видят и не находят.')"
            :title="__('Включить режим невидимки? (:name)', ['name' => $name])"
            :confirm="__('Включить')"
            :message="__('Другие участницы перестанут видеть её в каталоге, поиске, рекомендациях и AI-помощнике, и она не сможет публиковать инициативы. Сама она пользуется кабинетом как обычно, рассылки получает. Уведомление ей не отправляется. Выключить можно в любой момент.')" />
    @endif
@endif

@if($part === 'switches' && $blocked)
    <x-admin.profile-status-badge :status="$profile->status" />
@endif

{{-- Блокировка: особая кнопка, работает для любой участницы в любое время --}}
@if($part !== 'switches')
    @if($blocked)
        <x-admin.confirm-button
            :action="route('admin.profiles.unblock', $profile)"
            :label="__('Разблокировать')"
            trigger="btn-unlock"
            :confirm="__('Да, разблокировать')"
            :hint="__('Участница заблокирована: войти в кабинет она не может. Нажмите, чтобы вернуть доступ.')"
            :title="__('Разблокировать участницу? (:name)', ['name' => $name])"
            :message="__('Вход в кабинет снова откроется (по почте и через Google), рассылки начнут приходить. Отметка «видима другим / скрыта от других» вернётся такой, какой была до блокировки. Ей ничего не отправляется: сообщите ей сами, что доступ восстановлен.')" />
    @else
        <x-admin.confirm-button
            :action="route('admin.profiles.block', $profile)"
            :label="__('Заблокировать')"
            trigger="btn-lock"
            :confirm="__('Да, заблокировать')"
            :danger="true"
            :hint="__('Закрывает вход в кабинет. Можно заблокировать любую участницу в любое время; блокировку можно снять.')"
            :title="__('Заблокировать участницу? (:name)', ['name' => $name])"
            :message="($approved
                    ? __('Вход в кабинет закроется сразу: если она сейчас внутри, её выбросит при следующем действии, а войти заново по почте или через Google она не сможет. Ей придёт уведомление, что доступ закрыт (в Telegram или письмом). ')
                    : __('Вход в кабинет закроется сразу, войти по почте или через Google она не сможет. Ей придёт вежливое уведомление об отказе (в Telegram или письмом). '))
                .__('Профиль пропадёт из каталога, рассылки перестанут приходить. Профиль, платежи и пакет в базе остаются, но выдать ей новый пакет будет нельзя. Блокировку можно снять кнопкой «Разблокировать»: данные вернутся как были.')" />
    @endif
@endif
